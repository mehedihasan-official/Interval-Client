// SLOW-MODE (remove later)
export function SlowModeProvider({ children }) { // SLOW-MODE (remove later)
  if (!slowModeEnabled) return children; // SLOW-MODE (remove later)
  return <EnabledSlowModeProvider>{children}</EnabledSlowModeProvider>; // SLOW-MODE (remove later)
} // SLOW-MODE (remove later)

// SLOW-MODE (remove later)
function EnabledSlowModeProvider({ children }) { // SLOW-MODE (remove later)
  const [initialLoadComplete, setInitialLoadComplete] = useState(isSlowModeBypassed()); // SLOW-MODE (remove later)
  const [showLoading, setShowLoading] = useState(false); // SLOW-MODE (remove later)

  useEffect(() => { // SLOW-MODE (remove later)
    if (isSlowModeBypassed()) return undefined; // SLOW-MODE (remove later)

    let mounted = true; // SLOW-MODE (remove later)
    const handleLoading = (event) => setShowLoading(event.detail > 0); // SLOW-MODE (remove later)
    window.addEventListener(LOADING_EVENT, handleLoading); // SLOW-MODE (remove later)
    delayInitialLoad().finally(() => { // SLOW-MODE (remove later)
      if (mounted) setInitialLoadComplete(true); // SLOW-MODE (remove later)
    }); // SLOW-MODE (remove later)

    return () => { // SLOW-MODE (remove later)
      mounted = false; // SLOW-MODE (remove later)
      window.removeEventListener(LOADING_EVENT, handleLoading); // SLOW-MODE (remove later)
    }; // SLOW-MODE (remove later)
  }, []); // SLOW-MODE (remove later)

  if (isSlowModeBypassed()) return children; // SLOW-MODE (remove later)
  if (!initialLoadComplete) return <SlowModeSpinner />; // SLOW-MODE (remove later)

  return ( // SLOW-MODE (remove later)
    <> {/* SLOW-MODE (remove later) */}
      {children} {/* SLOW-MODE (remove later) */}
      {showLoading && <SlowModeSpinner overlay />} {/* SLOW-MODE (remove later) */}
    </> // SLOW-MODE (remove later)
  ); // SLOW-MODE (remove later)
} // SLOW-MODE (remove later)
